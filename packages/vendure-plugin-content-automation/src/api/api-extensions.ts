import { gql } from 'graphql-tag';

export const adminApiExtensions = gql`
  "A successful content generation by a content automation strategy"
  type ContentAutomationUpdate implements Node {
    id: ID!
    createdAt: DateTime!
    updatedAt: DateTime!
    strategyName: String!
    languageCode: LanguageCode!
    "The hash of the input the content was generated from"
    hash: String!
    resultMessage: String
    "Dashboard URL of the updated entity, if provided by the strategy"
    entityUrl: String
  }

  type ContentAutomationUpdateList implements PaginatedList {
    items: [ContentAutomationUpdate!]!
    totalItems: Int!
  }

  # Filter and sort fields are generated by Vendure
  input ContentAutomationUpdateListOptions

  extend type Query {
    "Content automation updates in the active channel"
    contentAutomationUpdates(
      options: ContentAutomationUpdateListOptions
    ): ContentAutomationUpdateList!
  }
`;
